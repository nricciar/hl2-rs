#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_ascii_alnum_and_punctuation_has_a_glyph() {
        for c in b'A'..=b'Z' {
            let g = glyph(c as char);
            assert!(g.iter().any(|&b| b != 0), "{c:?} should not be blank");
        }
        for c in b'0'..=b'9' {
            let g = glyph(c as char);
            assert!(g.iter().any(|&b| b != 0), "{c:?} should not be blank");
        }
        for c in b"-.:/" {
            let c = *c;
            let g = glyph(c as char);
            assert!(g.iter().any(|&b| b != 0), "{c:?} should not be blank");
        }
    }

    #[test]
    fn unknown_char_is_blank() {
        let g = glyph('?');
        assert_eq!(g, [0u8; 7]);
    }
}
